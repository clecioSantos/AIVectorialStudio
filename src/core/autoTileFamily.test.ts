import {describe,it,expect} from 'vitest';
import {deriveTileVariant,generateTileFamily} from './autoTileFamily';
import type {Artwork} from './schema';
const base:Artwork={id:'original',name:'Terra',category:'terrain',prompt:'base',createdAt:'',modifiedAt:'',size:512,stylePatch:{},shapes:[{id:'ground',name:'Solo',type:'rect',x:0,y:0,width:512,height:512,rotation:0,opacity:1,fill:'#876543',stroke:'none',strokeWidth:0,texture:{kind:'stone',scale:1,intensity:.5}}]};
describe('automatic tile family',()=>{
 it('creates eleven unique reusable artworks from a single base',()=>{
  const out=generateTileFamily(base);
  expect(out.artworks).toHaveLength(11);
  expect(new Set(out.artworks.map(a=>a.id)).size).toBe(11);
  expect(Object.keys(out.family.variants)).toHaveLength(11);
  expect(out.family.autoGenerated).toBe(true);
 });
 it('preserves original shapes and vector textures and only decorates exposed edges',()=>{
  const center=deriveTileVariant(base,'center');
  const top=deriveTileVariant(base,'edge-top');
  expect(center.shapes).toHaveLength(1);
  expect(top.shapes).toHaveLength(2);
  expect(top.shapes[0].texture).toEqual(base.shapes[0].texture);
  expect(top.shapes[0].fill).toBe('#876543');
  expect(top.shapes[1].name).toBe('Superfície superior');
  expect(base.shapes).toHaveLength(1);
 });
 it('generates corner trim on two edges',()=>{
  const corner=deriveTileVariant(base,'corner-tl');
  expect(corner.shapes.slice(1).map(s=>s.name)).toEqual(['Superfície superior','Borda esquerda']);
 });
});
